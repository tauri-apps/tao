//! Example app to test tao on Android and iOS. Also runs on desktop.
//!
//! See the README for how to run it.

use std::{collections::HashMap, sync::Mutex};

use tao::{
  event::{Event, StartCause, WindowEvent},
  event_loop::{ControlFlow, EventLoopBuilder, EventLoopProxy, EventLoopWindowTarget},
  window::{Window, WindowBuilder, WindowId},
};

#[derive(Debug)]
enum UserEvent {
  /// Create a new window (the "New window" button on Android).
  #[cfg_attr(not(target_os = "android"), allow(dead_code))]
  NewWindow,
}

static PROXY: Mutex<Option<EventLoopProxy<UserEvent>>> = Mutex::new(None);

#[cfg(any(target_os = "android", target_os = "ios"))]
fn stop_unwind<F: FnOnce() -> T, T>(f: F) -> T {
  match std::panic::catch_unwind(std::panic::AssertUnwindSafe(f)) {
    Ok(t) => t,
    Err(err) => {
      eprintln!("attempt to unwind out of `rust` with err: {err:?}");
      std::process::abort()
    }
  }
}

#[cfg(any(target_os = "android", target_os = "ios"))]
fn _start_app() {
  stop_unwind(main);
}

/// Entry point called by the iOS project generated by cargo-mobile2,
/// and registers the JNI functions on Android.
#[no_mangle]
#[inline(never)]
#[cfg(any(target_os = "android", target_os = "ios"))]
pub extern "C" fn start_app() {
  #[cfg(target_os = "android")]
  tao::android_binding!(app_tauri, tao_mobile, Rust, android::setup, _start_app);

  #[cfg(target_os = "ios")]
  _start_app()
}

pub fn main() {
  init_logging();

  let event_loop = EventLoopBuilder::<UserEvent>::with_user_event().build();
  *PROXY.lock().unwrap() = Some(event_loop.create_proxy());

  let mut windows = HashMap::<WindowId, Window>::new();

  event_loop.run(move |event, target, control_flow| {
    *control_flow = ControlFlow::Wait;

    match event {
      Event::NewEvents(StartCause::Init) => {
        // claims the activity (Android) or scene (iOS) that launched the app
        add_window(&mut windows, target, WindowBuilder::new());
      }

      Event::UserEvent(UserEvent::NewWindow) => {
        let builder = WindowBuilder::new();
        // creates a new activity, which must not trigger `Event::ActivityRequested`
        #[cfg(target_os = "android")]
        let builder = {
          use tao::platform::android::WindowBuilderExtAndroid;
          builder.with_activity_name("MainActivity".into())
        };
        add_window(&mut windows, target, builder);
      }

      // the system created an activity on its own, e.g. the app was launched again
      // after all of its activities were finished while the process was still alive
      #[cfg(target_os = "android")]
      Event::ActivityRequested {
        activity_id,
        activity_name,
      } => {
        use tao::platform::android::WindowBuilderExtAndroid;
        log::info!("[e2e] activity-requested activity={activity_id} name={activity_name}");
        add_window(
          &mut windows,
          target,
          WindowBuilder::new().with_activity_id(activity_id),
        );
      }

      // e.g. on iPad the user requested a new window from the app icon
      #[cfg(target_os = "ios")]
      Event::SceneRequested { scene, .. } => {
        log::info!("[e2e] scene-requested scene={scene:?}");
      }

      Event::Opened { urls } => log::info!("opened: {urls:?}"),

      Event::WindowEvent {
        window_id,
        event:
          event @ (WindowEvent::Started
          | WindowEvent::Resumed
          | WindowEvent::Suspended
          | WindowEvent::Stopped
          | WindowEvent::Focused(_)),
        ..
      } => log::info!("window {window_id:?}: {event:?}"),

      Event::WindowEvent {
        window_id,
        event: WindowEvent::CloseRequested | WindowEvent::Destroyed,
        ..
      } => {
        if let Some(window) = windows.remove(&window_id) {
          log::info!("[e2e] window-closed {}", describe(&window));
          #[cfg(target_os = "android")]
          android::window_detached(&window);
          drop(window);
        }
        // mobile apps are not supposed to exit on their own
        #[cfg(not(any(target_os = "android", target_os = "ios")))]
        if windows.is_empty() {
          *control_flow = ControlFlow::Exit;
        }
      }

      _ => (),
    }
  });
}

fn add_window(
  windows: &mut HashMap<WindowId, Window>,
  target: &EventLoopWindowTarget<UserEvent>,
  builder: WindowBuilder,
) {
  match builder.with_title("tao mobile").build(target) {
    Ok(window) => {
      log::info!("[e2e] window-created {}", describe(&window));
      #[cfg(target_os = "android")]
      android::window_attached(&window);
      windows.insert(window.id(), window);
    }
    Err(e) => log::error!("[e2e] window-create-failed error={e}"),
  }
}

/// Identifies a window in the logs, which are checked by the e2e tests (see the README).
fn describe(window: &Window) -> String {
  #[cfg(target_os = "android")]
  {
    use tao::platform::android::WindowExtAndroid;
    format!("activity={}", window.activity_id())
  }
  #[cfg(not(target_os = "android"))]
  format!("window={:?}", window.id())
}

#[cfg(target_os = "android")]
fn init_logging() {
  android_logger::init_once(
    android_logger::Config::default()
      .with_max_level(log::LevelFilter::Debug)
      .with_tag("tao-mobile"),
  );
}

#[cfg(not(target_os = "android"))]
fn init_logging() {
  let _ =
    env_logger::Builder::from_env(env_logger::Env::default().default_filter_or("info")).try_init();
}

/// Shows on each activity whether a tao window is attached to it.
#[cfg(target_os = "android")]
mod android {
  use std::{
    collections::HashMap,
    sync::{LazyLock, Mutex, OnceLock},
  };

  use tao::{
    platform::android::{
      prelude::{
        jni::{
          objects::{GlobalRef, JClass},
          JNIEnv, JavaVM,
        },
        ndk::looper::ThreadLooper,
      },
      WindowExtAndroid,
    },
    window::Window,
  };

  struct Activity {
    object: GlobalRef,
    has_window: bool,
  }

  static VM: OnceLock<JavaVM> = OnceLock::new();
  static ACTIVITIES: LazyLock<Mutex<HashMap<i32, Activity>>> = LazyLock::new(Default::default);

  /// Called by tao in `onCreate` for every activity.
  pub unsafe fn setup(
    _package: &str,
    mut env: JNIEnv,
    _looper: &ThreadLooper,
    activity: GlobalRef,
  ) {
    // runs before `main` for the first activity
    super::init_logging();
    let _ = VM.set(env.get_java_vm().unwrap());
    let id = activity_id(&mut env, &activity);
    log::info!("[e2e] activity-created activity={id}");

    let mut activities = ACTIVITIES.lock().unwrap();
    // an activity recreated due to a configuration change keeps its ID and its window
    let has_window = activities.get(&id).is_some_and(|a| a.has_window);
    activities.insert(
      id,
      Activity {
        object: activity,
        has_window,
      },
    );
    drop(activities);
    if has_window {
      update_status(id);
    }
  }

  pub fn window_attached(window: &Window) {
    let id = window.activity_id();
    if let Some(activity) = ACTIVITIES.lock().unwrap().get_mut(&id) {
      activity.has_window = true;
    }
    update_status(id);
  }

  /// The window is closed when its activity is destroyed, so we can forget about the activity.
  pub fn window_detached(window: &Window) {
    ACTIVITIES.lock().unwrap().remove(&window.activity_id());
  }

  fn update_status(id: i32) {
    let Some(vm) = VM.get() else { return };
    let mut env = vm.attach_current_thread_as_daemon().unwrap();
    let activities = ACTIVITIES.lock().unwrap();
    let Some(activity) = activities.get(&id) else {
      return;
    };
    let status = if activity.has_window {
      "tao window attached"
    } else {
      "no tao window attached"
    };
    let status = env.new_string(status).unwrap();
    env
      .call_method(
        &activity.object,
        "setStatus",
        "(Ljava/lang/String;)V",
        &[(&status).into()],
      )
      .unwrap();
  }

  fn activity_id(env: &mut JNIEnv, activity: &GlobalRef) -> i32 {
    env
      .call_method(activity, "getId", "()I", &[])
      .unwrap()
      .i()
      .unwrap()
  }

  /// Called by the "New window" button.
  #[no_mangle]
  unsafe extern "C" fn Java_app_tauri_tao_1mobile_Rust_requestWindow(_env: JNIEnv, _class: JClass) {
    if let Some(proxy) = &*super::PROXY.lock().unwrap() {
      let _ = proxy.send_event(super::UserEvent::NewWindow);
    }
  }
}
